import type { InterestFor } from './types';

/** Tone/CTA copy from Start «для себя / для клиента» — does not trim evidence. */
export function copyForInterest(interest: InterestFor) {
  const isClient = interest === 'client';
  return {
    isClient,
    startClientHint: isClient
      ? 'Заполните комнату клиента — получите готовый аргумент для показа.'
      : null,
    roomBasicsSubtitle: isClient
      ? 'Обязательные поля комнаты клиента — для профиля и ссылки на калькулятор.'
      : 'Обязательные поля — для профиля и ссылки на калькулятор.',
    resultSubtitle: isClient
      ? 'Ориентир комфорта для комнаты клиента и следующий шаг к расчёту'
      : 'Ориентир комфорта для вашей комнаты и следующий шаг к расчёту',
    leadHelp: isClient
      ? 'Разберём случай клиента, подберём материал.'
      : 'Разберём ваш случай, подберём материал.',
    ribbonTitle: isClient ? 'Итог для комнаты клиента' : 'Итог для вашей комнаты',
    ribbonClose: isClient
      ? 'Для такой комнаты MultiFrame — сильный выбор: акустика, монтаж и комфорт сходятся в одной системе под натяжной потолок клиента.'
      : 'Для такой комнаты MultiFrame — сильный выбор: акустика, монтаж и комфорт сходятся в одной системе под ваш натяжной.',
    nextStepHint: isClient
      ? 'Передайте клиенту расчёт или оставьте заявку — менеджеру уйдёт сводка.'
      : 'Вы уже видите профиль комнаты — в калькуляторе останется уточнить комплектацию.',
    leadSuccessExtra: isClient
      ? 'Сводка сохранена для менеджера (консоль демо).'
      : null,
  };
}
